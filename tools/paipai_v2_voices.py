"""Acted voice auditions via the official Qwen3-TTS public VoiceDesign demo.

No celebrity cloning. No synthetic success fallback: a backend failure is kept
and blocks missing auditions. Existing hash-verified performances are reused.
"""
import argparse
from pathlib import Path
import json
import time
import requests
from video_rush.common import ROOT,read,write,sha,digest,run,duration
from video_rush.narration import audio_metrics


def generate(spec,out,local_model=None,only=None):
    folder=out/'voices';folder.mkdir(parents=True,exist_ok=True);index=[]
    backend=spec['voice_backend'];model=None
    if local_model:
        import torch
        import soundfile as sf
        from qwen_tts import Qwen3TTSModel
        torch.set_num_threads(4);torch.set_num_interop_threads(1)
        print('Loading real local Qwen3-TTS VoiceDesign on CPU',flush=True)
        model=Qwen3TTSModel.from_pretrained(str(local_model),device_map='cpu',dtype=torch.bfloat16,attn_implementation='sdpa')
        backend={**backend,'name':'Qwen3-TTS VoiceDesign 1.7B, local CPU bfloat16','runtime':'torch 2.8.0+cpu; qwen-tts 0.1.1','host':None,'endpoint':None}
        print('Model loaded',flush=True)
    for sequence,a in enumerate(spec['auditions']):
        if only and a['id']!=only:continue
        id=a['id'];target=folder/(id+'.m4a');receipt=folder/(id+'.json')
        key=digest({'audition':a,'backend':backend,'normalization':'-17 LUFS; trim only silence; AAC 96k mono'})
        if target.exists() and receipt.exists():
            old=read(receipt)
            if old.get('key')==key and old['sha256']==sha(target):index.append(old);print('Voice cached',id,flush=True);continue
        base=spec['voice_backend']['host']+'/gradio_api/call/generate_voice_design';request=[a['text'],'Chinese',a['direction']]
        try:
            raw=folder/(id+'-original.wav')
            if model is not None:
                torch.manual_seed(20261102+sequence);started=time.monotonic()
                waves,sr=model.generate_voice_design(text=a['text'],language='Chinese',instruct=a['direction'],non_streaming_mode=True,max_new_tokens=256)
                sf.write(str(raw),waves[0],sr);eid=None;payload=[None,'Actual local inference, %.2f seconds'%(time.monotonic()-started)]
            else:
                r=requests.post(base,json={'data':request},timeout=30);r.raise_for_status();eid=r.json()['event_id'];events=[];payload=None;event=None
                with requests.get(base+'/'+eid,stream=True,timeout=(20,90)) as stream:
                    stream.raise_for_status()
                    for line in stream.iter_lines(decode_unicode=True):
                        if not line:continue
                        events.append(line)
                        if line.startswith('event:'):event=line[6:].strip()
                        if line.startswith('data:') and event=='error':raise RuntimeError('Voice backend error: '+line[5:])
                        if line.startswith('data:') and event=='complete':payload=json.loads(line[5:])
                if not payload or not payload[0] or 'url' not in payload[0]:raise RuntimeError('No voice returned: '+str(payload))
                response=requests.get(payload[0]['url'],timeout=45);response.raise_for_status();raw.write_bytes(response.content)
            metrics=audio_metrics(raw)
            if not metrics['audible_signal']:raise ValueError('Backend returned silent audio')
            # Retain onset consonants and breathing; do not squeeze performances
            # back into the old flat voice's timing.
            run(['ffmpeg','-v','error','-y','-i',raw,'-af','silenceremove=start_periods=1:start_duration=0.05:start_threshold=-55dB:start_silence=0.08,loudnorm=I=-17:TP=-1.5:LRA=11','-ar','48000','-ac','1','-c:a','aac','-b:a','96k','-movflags','+faststart',target],timeout=90)
            result={**a,'key':key,'backend':backend,'event_id':eid,'backend_status':payload[1],'raw_sha256':sha(raw),'sha256':sha(target),'duration':duration(target),'metrics':audio_metrics(target),'processing':'Silence-onset trim with 80ms retention; loudness normalization only. Acting differences generated by model, not gain/pitch variants.','review_status':'Actual generated waveform; acting and character identity pending user audition'}
            write(receipt,result);index.append(result);print('Voice generated',id,round(result['duration'],2),flush=True)
        except Exception as e:
            write(folder/(id+'.failure.json'),{'id':id,'backend':spec['voice_backend'],'error':str(e),'request':request,'status':'failed, not replaced with silence or another performance'});raise
    if not only:write(out/'voice-candidates.json',index)
    return index


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--spec',default='episodes/ep008-v2-av-review.json');p.add_argument('--output',default='build/episodes/ep008-v2-review');p.add_argument('--local-model',type=Path);p.add_argument('--only');a=p.parse_args();generate(read(a.spec),Path(a.output),a.local_model,a.only)
